import { Envelope } from "@domain/envelope"
import { PeerJoined, PeerLeft } from "@domain/built-in-envelopers"
import { PeerManifest } from "@domain/peer-manifest"
import { EnvelopeFactory } from "./envelope-factory"

export type NetworkRecord = {
	id: string
	name: string
	peerIds: string[]
}

export class Network {
	private readonly id: string
	private name: string
	private peerIds: string[]

	private constructor(id: string, name: string, peerIds: string[] = []) {
		this.id = id
		this.name = name
		this.peerIds = [...peerIds]
	}

	getId(): string {
		return this.id
	}

	getName(): string {
		return this.name
	}

	getPeerIds(): string[] {
		return [...this.peerIds]
	}

	hasPeer(peerId: string): boolean {
		return this.peerIds.includes(peerId)
	}

	connect(manifest: PeerManifest): PeerJoined {
		if (this.hasPeer(manifest.id)) {
			throw new Error("Peer already connected")
		}

		this.peerIds.push(manifest.id)

		return EnvelopeFactory.peerJoined(this.id, manifest)
	}

	disconnect(peerId: string): PeerLeft {
		if (!this.hasPeer(peerId)) {
			throw new Error("Peer not connected")
		}

		this.peerIds = this.peerIds.filter((id) => id !== peerId)

		return EnvelopeFactory.peerLeft(this.id, peerId)
	}

	validateEnvelope(envelope: Envelope): void {
		if (envelope.getNetworkId() !== this.id) {
			throw new Error("Envelope belongs to another network")
		}

		if (!this.hasPeer(envelope.getSenderId())) {
			throw new Error("Sender not connected")
		}

		if (envelope.getType() === "peer.joined" || envelope.getType() === "peer.left") {
			throw new Error("Membership envelopes are generated by Network")
		}
	}

	toRecord(): NetworkRecord {
		return {
			id: this.id,
			name: this.name,
			peerIds: this.getPeerIds(),
		}
	}

	static create(name: string): Network {
		return new Network(crypto.randomUUID(), name)
	}

	static rehydrate(record: NetworkRecord): Network {
		return new Network(record.id, record.name, record.peerIds)
	}
}
